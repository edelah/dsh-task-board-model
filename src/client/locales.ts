/** The dictionary key union. */
export type TaskBoardKey = keyof typeof zh

/** The settings-card slice of the task-board dictionary. */
export type SettingsCardKey = TaskBoardKey

/** Locale supplied by DSH's locale runtime after the client mounts. */
let runtimeLocale: string | undefined

/** Set or clear the runtime locale used by task-board copy. */
export function setTaskBoardLocale(locale: string | undefined): void {
  runtimeLocale = locale
}

/** Active dictionary, picked for the active locale at call time. */
export function dictionary(): Record<TaskBoardKey, string> {
  const lang = runtimeLocale
    ?? (typeof document !== 'undefined' ? document.documentElement.lang : 'zh')
  return lang.toLowerCase().startsWith('en') ? en : zh
}

/** Translate a key with optional {name} template params. */
export function t(key: TaskBoardKey, params?: Record<string, string>): string {
  let text: string = dictionary()[key]
  if (params !== undefined) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, value)
    }
  }
  return text
}
